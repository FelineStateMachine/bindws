// Folds connection-templates/*.jsonc into src/gen/connections.ts, the app
// shortcut library the relay offers, in file order. `--check` rebuilds in
// memory and fails when the committed file is stale, so typecheck catches a
// forgotten rebuild.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { stripComments } from "../check/jsonc.mjs";

const DIR = new URL("../../connection-templates/", import.meta.url);
const OUT = new URL("../../src/gen/connections.ts", import.meta.url);
const files = readdirSync(DIR).filter((f) => f.endsWith(".jsonc")).sort();
// The folder's README is the catalog: every template has a row there.
const readme = readFileSync(new URL("README.md", DIR), "utf8");
const missing = files.filter((f) => !readme.includes(`](${f})`));
if (missing.length) {
  console.error(`connection-templates/README.md has no row for: ${missing.join(", ")}`);
  process.exit(1);
}
const templates = files.map((f) => {
  const doc = JSON.parse(stripComments(readFileSync(new URL(f, DIR), "utf8")));
  delete doc.$schema;
  return { name: f.replace(/^\d+-/, "").replace(/\.jsonc$/, ""), document: doc };
});
const file = `// Generated by scripts/build/build-connections.mjs from connection-templates/. Do not edit; run npm run build:connections.
export const CONNECTION_LIBRARY: { name: string; document: unknown }[] = ${JSON.stringify(templates, null, 2)};
`;
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (cur !== file) {
    console.error("src/gen/connections.ts is stale: run npm run build:connections");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, file);
  console.log(`src/gen/connections.ts: ${templates.length} connection templates`);
}
