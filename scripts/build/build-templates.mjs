// Folds relay-templates/*.jsonc into src/gen/templates.ts, the presets the
// relay offers, in file order. `--check` rebuilds in memory and fails when
// the committed file is stale, so typecheck catches a forgotten rebuild.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { stripComments } from "../check/jsonc.mjs";

const DIR = new URL("../../relay-templates/", import.meta.url);
const OUT = new URL("../../src/gen/templates.ts", import.meta.url);
const files = readdirSync(DIR).filter((f) => f.endsWith(".jsonc")).sort();
const templates = files.map((f) => {
  const doc = JSON.parse(stripComments(readFileSync(new URL(f, DIR), "utf8")));
  delete doc.$schema;
  return { name: f.replace(/^\d+-/, "").replace(/\.jsonc$/, ""), document: doc };
});
const file = `// Generated by scripts/build/build-templates.mjs from relay-templates/. Do not edit; run npm run build:templates.
export const TEMPLATES: { name: string; document: unknown }[] = ${JSON.stringify(templates, null, 2)};
`;
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (cur !== file) {
    console.error("src/gen/templates.ts is stale: run npm run build:templates");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, file);
  console.log(`src/gen/templates.ts: ${templates.length} templates`);
}
